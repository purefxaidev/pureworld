export function buildSystemInstruction(npcId, hero) {
  const n = NPCS[npcId];
  let ctx = "";
  if (hero) {
    ctx = `\n\nข้อมูลผู้เล่นตอนนี้: ฮีโรอีนชื่อ "${hero.name}" สายอาชีพ ${hero.role} เลเวล ${hero.level}. ทักทายและตอบให้เข้ากับเลเวลของเธอ`;
  }
  return `${n.persona}\n\n${BASE_RULES}${ctx}`;
}
